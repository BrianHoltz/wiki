def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("20_questions_hierarchy.yaml"),
        help="YAML path to write (default: 20_questions_hierarchy.yaml)",
    )
    parser.add_argument(
        "--html-output",
        type=Path,
        default=Path("index.html"),
        help="HTML path to write (default: index.html)",
    )
    args = parser.parse_args()
    tree = make_tree()
    yaml_output = render_yaml(tree, "20_questions_noun_hierarchy")
    html_output = render_html(tree, "20 Questions Noun Hierarchy")
    args.output.write_text(yaml_output, encoding="utf-8")
    args.html_output.write_text(html_output, encoding="utf-8")
    print(f"Wrote {args.output} ({yaml_output.count(chr(10)) - 1} lines)")
    print(f"Wrote {args.html_output} ({html_output.count(chr(10)) - 1} lines)")


if __name__ == "__main__":
    main()
