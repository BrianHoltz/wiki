#!/usr/bin/env python3
"""Generate a practical, question-oriented noun hierarchy for 20 Questions.

The ontology is deliberately organized by high-value game questions instead of
strict biological or academic taxonomy.  It is dependency-free and deterministic:

    python3 generate_20q_hierarchy.py
    python3 generate_20q_hierarchy.py --output my-20q-tree.yaml

The output is ordinary YAML with comments on every branch through level four.
Empty mappings are terminal noun categories, so IntelliJ can fold every branch.
"""

from __future__ import annotations

import argparse
import html
from collections import OrderedDict
from pathlib import Path
from typing import Mapping


Tree = OrderedDict[str, "Tree | None"]


def branch(question: str, *groups: Tree, **children: Tree | None) -> Tree:
    """Attach a discriminator to a mapping without adding YAML machinery."""
    result: Tree = OrderedDict()
    result["__question__"] = question  # consumed by the renderer
    for group in groups:
        result.update(group)
    result.update(children)
    return result


def leaves(*names: str) -> Tree:
    return OrderedDict((name, None) for name in names)


def render_yaml(tree: Mapping[str, Tree | None], root_name: str) -> str:
    lines = [
        "# Generated by generate_20q_hierarchy.py",
        "# Ask the highest-level questions first; switch branches as soon as the",
        "# answer sharply reduces the remaining candidate set.",
        f"{root_name}:",
    ]

    def emit(mapping: Mapping[str, Tree | None], indent: int, level: int) -> None:
        question = mapping.get("__question__")
        for name, child in mapping.items():
            if name == "__question__":
                continue
            display_name = name.replace("_", " ")
            suffix = ""
            if child is not None and level <= 4:
                child_question = child.get("__question__", "Does it belong to this category?")
                suffix = f"  # Q: {child_question}"
            lines.append(" " * indent + f"{display_name}:{suffix}")
            if child:
                emit(child, indent + 2, level + 1)

    emit(tree, 2, 1)
    return "\n".join(lines) + "\n"


def render_html(tree: Mapping[str, Tree | None], title: str) -> str:
    """Render a self-contained browser with collapsible branches and questions."""
    def searchable(mapping: Mapping[str, Tree | None]) -> str:
        values = []
        for name, child in mapping.items():
            if name != "__question__":
                values.append(name.replace("_", " "))
                if child:
                    values.append(searchable(child))
        return " ".join(values)

    def emit(mapping: Mapping[str, Tree | None], level: int, path: tuple[str, ...]) -> str:
        parts = []
        for name, child in mapping.items():
            if name == "__question__":
                continue
            label = name.replace("_", " ")
            escaped_label = html.escape(label)
            escaped_path = html.escape(" / ".join(path + (label,)))
            if child:
                question = html.escape(child.get("__question__", "Does it belong here?"))
                search_text = html.escape(searchable(child), quote=True)
                open_attr = " open" if level == 1 else ""
                parts.append(
                    f'<details class="node" data-search="{search_text}"{open_attr}>'
                    f'<summary>{escaped_label}</summary>'
                    f'<div class="question"><strong>Suggested question:</strong> {question}</div>'
                    f'<div class="path">{escaped_path}</div>'
                    f'<div class="children">{emit(child, level + 1, path + (label,))}</div>'
                    "</details>"
                )
            else:
                parts.append(
                    f'<div class="leaf" data-search="{html.escape(label.lower(), quote=True)}">'
                    f'<span>{escaped_label}</span>'
                    f'<small>{escaped_path}</small>'
                    "</div>"
                )
        return "\n".join(parts)

    root_question = html.escape(tree.get("__question__", "What kind of thing is it?"))
    body = emit(tree, 1, ())
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>
:root {{ color-scheme: light dark; --accent: #2f6feb; --panel: #f6f8fa; --muted: #57606a; }}
body {{ font: 15px/1.45 system-ui, -apple-system, sans-serif; margin: 0 auto; max-width: 1100px; padding: 24px; }}
h1 {{ margin-bottom: 6px; }}
.intro, .question {{ background: var(--panel); border-left: 4px solid var(--accent); padding: 10px 14px; margin: 10px 0; }}
.controls {{ display: flex; gap: 8px; flex-wrap: wrap; margin: 18px 0; }}
input {{ flex: 1 1 280px; padding: 9px; border: 1px solid #8c959f; border-radius: 6px; }}
button {{ padding: 9px 12px; border: 1px solid #8c959f; border-radius: 6px; cursor: pointer; }}
details {{ margin: 4px 0 4px 12px; }}
summary {{ cursor: pointer; font-weight: 650; padding: 5px; }}
summary:hover {{ background: var(--panel); }}
.children {{ border-left: 1px solid #8c959f; margin-left: 9px; padding-left: 8px; }}
.question {{ color: var(--muted); font-size: .94em; }}
.path, .leaf small {{ color: var(--muted); font-size: .82em; }}
.leaf {{ display: flex; gap: 12px; justify-content: space-between; padding: 3px 6px 3px 25px; }}
.leaf:hover {{ background: var(--panel); }}
[hidden] {{ display: none !important; }}
</style>
</head>
<body>
<h1>{html.escape(title)}</h1>
<div class="intro"><strong>Opening question:</strong> {root_question}</div>
<div class="controls">
  <input id="search" type="search" placeholder="Search nouns or categories...">
  <button id="expand">Expand all</button>
  <button id="collapse">Collapse all</button>
</div>
<main id="tree">{body}</main>
<script>
const nodes = [...document.querySelectorAll(".node, .leaf")];
const search = document.querySelector("#search");
search.addEventListener("input", () => {{
  const query = search.value.trim().toLowerCase();
  document.querySelectorAll(".node, .leaf").forEach((node) => {{
    const match = !query || node.dataset.search.toLowerCase().includes(query);
    node.hidden = !match;
    if (match && node.classList.contains("node") && query) node.open = true;
  }});
  if (query) document.querySelectorAll(".node").forEach((node) => {{
    if (node.querySelector(".leaf:not([hidden]), .node:not([hidden])")) node.open = true;
  }});
}});
document.querySelector("#expand").onclick = () => document.querySelectorAll(".node").forEach(n => n.open = true);
document.querySelector("#collapse").onclick = () => document.querySelectorAll(".node").forEach(n => n.open = false);
</script>
</body>
</html>
"""


